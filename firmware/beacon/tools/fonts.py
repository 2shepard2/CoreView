def pack(name, glyphs, height, first, last, extra):
    chars = [chr(c) for c in range(first, last + 1)] + list(extra)
    data, index = [], []
    for ch in chars:
        rows = glyphs.get(ch)
        if rows is None:
            index.append((0, 0))
            continue
        width = max(len(r) for r in rows)
        rows = [r.ljust(width, ".") for r in rows] + ["." * width] * (height - len(rows))
        assert len(rows) == height, (name, ch, len(rows))
        offset = len(data)
        # Column-major: one uint16 per column, bit y set when lit.
        for x in range(width):
            bits = 0
            for y in range(height):
                if rows[y][x] == "#":
                    bits |= 1 << y
            data.append(bits)
        index.append((offset, width))
    out = [f"static const uint16_t {name}_cols[] = {{"]
    for i in range(0, len(data), 16):
        out.append("  " + ", ".join(f"0x{v:04x}" for v in data[i:i + 16]) + ",")
    out.append("};")
    out.append(f"static const uint16_t {name}_index[][2] = {{")
    out.append("  " + ", ".join(f"{{{o}, {w}}}" for o, w in index))
    out.append("};")
    return "\n".join(out)


def main():
    missing = [chr(c) for c in range(32, 127) if chr(c) not in SMALL]
    assert not missing, missing
    print("// Generated by tools/fonts.py. Do not edit by hand.")
    print("#pragma once")
    print("#include <cstdint>")
    print("namespace beacon_fonts {")
    print(f"static const int small_height = {SMALL_HEIGHT};")
    print(f"static const int big_height = {BIG_HEIGHT};")
    print(pack("small", SMALL, SMALL_HEIGHT, 32, 126, "°"))
    print(pack("big", BIG, BIG_HEIGHT, 32, 58, ""))
    print("}  // namespace beacon_fonts")


if __name__ == "__main__":
    sys.exit(main())
